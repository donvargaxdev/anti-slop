func TestNolintNeedsALinterAndAReasonAfterIt(t *testing.T) {
	for _, tc := range []struct {
		comment string
		want    string
	}{
		{"//nolint:gosec // the argument is checked at its edge", ""},
		{"//nolint:gosec,revive the reason without slashes", ""},
		{"//nolint:gosec", reasonNolint},
		{"//nolint:gosec ", reasonNolint},
		{"//nolint:gosec //", reasonNolint},
		{"//nolint:gosec //   ", reasonNolint},
		{"//nolint", reasonNolint},
		{"//nolint // a reason but no linter", reasonNolint},
		{"//nolint: gosec // a space after the colon names no linter", reasonNolint},
		{"//nolint:gosec// no space before the reason", reasonNolint},
		{"//nolintx", reasonNolint},
		{"// nolint:gosec // a space before nolint is no directive", reasonUnread},
	} {
		file := parse(t, "package p\n\n"+tc.comment+"\nfunc F() {}\n")
		got := ""
		if found := findings(file); len(found) > 0 {
			got = found[0].Message
		}
		if got != tc.want {
			t.Errorf("%q: finding %q, want %q", tc.comment, got, tc.want)
		}
	}
}

func TestADirectiveIsReadOnlyWithoutASpaceAfterTheSlashes(t *testing.T) {
	for _, tc := range []struct {
		comment string
		want    string
	}{
		{"//go:noinline", ""},
		{"//go:build linux", ""},
		{"// go:noinline", reasonUnread},
		{"//line x.go:10", ""},
		{"//linex", reasonUnread},
		{"/*line x.go:10*/", ""},
		{"/* line x.go:10 */", reasonUnread},
		{"// Code generated by x; DO NOT EDIT.", ""},
		{"// Code generated by x; DO NOT EDIT", reasonUnread},
		{"// Code generated", reasonUnread},
		{"// itos-cc mutation: 1 killed", ""},
	} {
		file := parse(t, "package p\n\nfunc F() {}\n\n"+tc.comment+"\n")
		got := ""
		if found := findings(file); len(found) > 0 {
			got = found[0].Message
		}
		if got != tc.want {
			t.Errorf("%q: finding %q, want %q", tc.comment, got, tc.want)
		}
	}
}

func TestAMutationBlockEndsAtItsClosingLine(t *testing.T) {
	file := parse(t, "package p\n\n// itos-cc mutation: 1 killed\n// survived: line 1\n// end itos-cc mutation\n// after the block\nfunc F() {}\n")
	found := findings(file)
	if len(found) != 1 || file.Comments[0].List[3].Slash != found[0].Pos {
		t.Fatalf("findings = %v, want only the comment after the block", found)
	}
}

func TestOnlyALicenseHeaderBeforeThePackageClauseIsLeftAlone(t *testing.T) {
	for _, tc := range []struct {
		name, source string
		want         int
	}{
		{"header", "// Copyright 2026 A.\n\npackage p\n", 0},
		{"license word", "// MIT License\n\npackage p\n", 0},
		{"british spelling", "// Licence: MIT\n\npackage p\n", 0},
		{"after build constraint", "//go:build cgo\n\n// Copyright 2026 A.\n// All rights reserved.\n\npackage p\n", 0},
		{"after paired build constraints", "//go:build cgo\n// +build cgo\n\n// Copyright 2026 A.\n\npackage p\n", 0},
		{"after legacy build constraint", "// +build cgo\n\n// Copyright 2026 A.\n\npackage p\n", 0},
		{"after generated marker", "// Code generated by x; DO NOT EDIT.\n\n// Copyright 2026 A.\n\npackage p\n", 0},
		{"ordinary comment in the constraint group", "//go:build cgo\n// ordinary explanation\n\n// Copyright 2026 A.\n\npackage p\n", 2},
		{"ordinary comment in the package body", "package p\n\n// +build cgo\nvar F int\n", 1},
		{"no license in the first block", "// the package\n\npackage p\n", 1},
		{"license block that is not the first", "// the package\n\n// Copyright 2026 A.\n\npackage p\n", 2},
		{"license after the package clause", "package p\n\n// Copyright 2026 A.\nfunc F() {}\n", 1},
		{"every comment of the header", "// Copyright 2026 A.\n// All rights reserved.\n// Anything else.\n\npackage p\n", 0},
	} {
		if got := len(findings(parse(t, tc.source))); got != tc.want {
			t.Errorf("%s: %d findings, want %d", tc.name, got, tc.want)
		}
	}
}

func TestProvenanceNoticesArePreservedWhereTheyAppear(t *testing.T) {
	file := parse(t, `// Compile-first mechanics adapted from itos-container T-10, f6f339c (AGPL-3.0).

// Ownership/linked graph probes follow itos-cc's architecture-check design.
package p

// Harvested with the owner's permission (CONTRIBUTORS.md) from
// github.com/org/project.
func F() {}

// Copied from the object as written.
func G() {}

// This follows the user's preference.
func H() {}
`)
	found := findings(file)
	if len(found) != 2 || found[0].Pos != file.Comments[3].Pos() || found[1].Pos != file.Comments[4].Pos() {
		t.Fatalf("findings = %v, want only the ordinary comments", found)
	}
}

func TestOnlyThePreambleCgoConsumesIsPreserved(t *testing.T) {
	for _, tc := range []struct {
		name, imports string
	}{
		{"single import", "// #include <stdlib.h>\nimport \"C\""},
		{"single import in parentheses", "/* #include <stdlib.h> */\nimport (\n\"C\"\n)"},
		{"grouped import", "import (\n/* #include <stdlib.h> */\n\"C\"\n\"fmt\"\n)"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			file := parse(t, "package p\n\n"+tc.imports+"\n\n// Go documentation\nvar F int\n")
			found := findings(file)
			if len(found) != 1 || found[0].Pos != file.Comments[1].Pos() {
				t.Fatalf("findings = %v, want only the Go documentation", found)
			}
		})
	}
}

func TestImportCommentsThatCgoDoesNotConsumeAreReported(t *testing.T) {
	for _, tc := range []struct {
		name, imports string
	}{
		{"separated from import", "// #include <stdlib.h>\n\nimport \"C\""},
		{"trailing import", "import \"C\" // #include <stdlib.h>"},
		{"ordinary import", "// #include <stdlib.h>\nimport \"fmt\""},
		{"before a group with multiple imports", "// #include <stdlib.h>\nimport (\n\"C\"\n\"fmt\"\n)"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			file := parse(t, "package p\n\n"+tc.imports+"\n")
			found := findings(file)
			if len(found) != 1 || found[0].Pos != file.Comments[0].Pos() {
				t.Fatalf("findings = %v, want the comment that is outside a cgo preamble", found)
			}
		})
	}
}

func parse(t *testing.T, source string) *ast.File {
	t.Helper()
	file, err := parser.ParseFile(token.NewFileSet(), "p.go", source, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	return file
}
